#!/usr/bin/env python3
"""Assemble a local complete candidate with code, dictionaries and input hashes."""
import argparse
import csv
import json
import shutil
import subprocess
from pathlib import Path
from bootstrap_data import digest

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--telemetry-candidate', type=Path, default=ROOT/'outputs/release_candidate/telemetry-v1-reviewed')
    parser.add_argument('--output-dir', type=Path, default=ROOT/'outputs/release_candidate/complete-v1')
    args = parser.parse_args()
    target = args.output_dir.resolve(); target.mkdir(parents=True, exist_ok=False)
    # Copy only explicit public code/config/documentation trees. Never traverse private/raw/output trees.
    for domain in ('src', 'scripts', 'config', 'docs', 'tests', 'publication/figure3'):
        for source in (ROOT/domain).rglob('*'):
            rel = source.relative_to(ROOT)
            if not source.is_file() or 'private' in rel.parts or '__pycache__' in rel.parts or source.name.endswith('_preview.png'):
                continue
            if source.suffix not in {'.py','.csv','.toml','.md','.txt','.svg','.png','.pdf'}:
                continue
            destination = target/rel; destination.parent.mkdir(parents=True, exist_ok=True);shutil.copy2(source,destination)
    for filename in ('pyproject.toml','README.md','.gitignore','.gitattributes'):
        shutil.copy2(ROOT/filename,target/filename)
    for source in (ROOT/'data/public').rglob('*.csv'):
        dest=target/source.relative_to(ROOT);dest.parent.mkdir(parents=True,exist_ok=True)
        if source.name == 'payment_ledger_anonymized.csv':
            with source.open(newline='') as f, dest.open('w',newline='') as output:
                reader=csv.DictReader(f)
                fields=[c for c in reader.fieldnames if c not in {'external_id','capex_note','description_original'}]
                writer=csv.DictWriter(output,fieldnames=fields);writer.writeheader()
                for row in reader:writer.writerow({c:row[c] for c in fields})
        else:shutil.copy2(source,dest)
    telemetry=target/'data/telemetry';telemetry.mkdir(parents=True)
    for name in ('HOP_daily_energy.zip','HOP_voltage_power_1min.zip','PowerWatch_voltage_frequency_2min.zip','DRC1_baseline_supplement.zip','data_sources.toml','manifest.json','README.md'):
        shutil.copy2(args.telemetry_candidate/name,telemetry/name)
    dictionaries=target/'dictionaries';dictionaries.mkdir()
    shutil.copy2(ROOT/'docs/data_dictionary_dhis2.md',dictionaries/'dhis2.md')
    shutil.copy2(ROOT/'docs/PUBLIC_DATA_DICTIONARY.md',dictionaries/'telemetry_payments.md')
    (target/'REPRODUCE.md').write_text('''# Reproduce the candidate package

This is a local review candidate, not an authorised public release. Proposed data/documentation licence: CC BY 4.0; proposed code licence: MIT. These are proposals pending confirmation, not applied licence grants.

Requires Python 3.11 or newer (the archive loader uses tomllib). Extract the package into an empty directory, then:

```bash
python -m venv .venv
source .venv/bin/activate
pip install -e '.[dev]'
python scripts/run_public_package.py
pytest
```

The runner verifies all packaged file hashes, imports the four telemetry archives and runs electricity, energy, Figure 3, timeline, payments, health and annex workflows. Outputs go to outputs/generated. Health uses public panels only; it does not reconstruct private source-cleaning/mapping audits.

Optional publication export: install `.[publication]`, then run `python scripts/export_figure3.py`. Read docs/FIGURE3_DELIVERY.md for source and denominator limitations. All six comparison values are reconstructed from selected source windows; alternatives and coverage are supplied. Energy topology and active windows retain provisional labels. Health summaries are descriptive, not a causal model.

Payment free-text notes, source transaction IDs and original descriptions were removed; calculation inputs are retained. The copied code/documentation are the current local snapshot, including changes not yet committed. Public figure source values are in publication/figure3; other figure/table source values are generated by the runner.

Exact dates and shared facility codes are retained for reproduction and remain subject to disclosure/rights review. No identified DHIS2 exports, private mapping, contact list or respondent-level survey is included. Telemetry originals/updates overlap: canonical selection and omitted-series flags apply. Full telemetry rows are present; missing sensors are not manufactured.
''')
    files=[]
    for p in sorted(target.rglob('*')):
        if p.is_file():
            entry={'path':p.relative_to(target).as_posix(),'bytes':p.stat().st_size,'sha256':digest(p)}
            if p.suffix=='.csv':
                with p.open(newline='') as f:
                    reader=csv.reader(f);entry['columns']=next(reader);entry['rows']=sum(1 for _ in reader)
            files.append(entry)
    manifest={'status':'local_candidate_pending_rights_and_disclosure_confirmation','proposed_code_licence':'MIT','proposed_data_licence':'CC-BY-4.0','source_git_commit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'local_snapshot_includes_uncommitted_changes':True,'files':files,'limitations':['Baseline source windows differ by facility; variable coverage','Provisional energy topology and active windows','Source DHIS2 cleaning not included','Exact dates and coded cross-domain links retained for review']}
    (target/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Built {len(files)} files at {target}')

if __name__=='__main__':main()
